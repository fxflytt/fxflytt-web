# Makes the browser copy of the price calculator from the one shared source (lib/pricing).
import json, re
src = open("lib/pricing/pricelist.js", encoding="utf-8").read()
src = re.sub(r"^export ", "", src, flags=re.M)
prices = json.load(open("lib/pricing/prices.json", encoding="utf-8"))
out = "/* Generated by add-prices.py from lib/pricing – do not edit. */\n(function(){\n" + src + \
      "\nwindow.FX_PRICES=" + json.dumps(prices, ensure_ascii=False) + ";\nwindow.fxComputePrice=computePrice;\n})();\n"
open("public/price-calc.js", "w", encoding="utf-8").write(out)
print("wrote public/price-calc.js")
